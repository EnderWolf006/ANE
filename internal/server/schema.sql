CREATE TABLE IF NOT EXISTS merchants (
 id bigint GENERATED BY DEFAULT AS IDENTITY (START WITH 1000) PRIMARY KEY,
 username text UNIQUE NOT NULL, name text NOT NULL, password_hash text NOT NULL,
 is_admin boolean NOT NULL DEFAULT false, enabled boolean NOT NULL DEFAULT true,
 merchant_key text NOT NULL, pool_limit integer NOT NULL DEFAULT 99 CHECK(pool_limit BETWEEN 1 AND 9999),
 order_ttl_minutes integer NOT NULL DEFAULT 10 CHECK(order_ttl_minutes BETWEEN 1 AND 60),
 payment_note text NOT NULL DEFAULT '请按显示的精确金额支付，勿修改金额或重复付款。<br>付款成功后本页会自动更新。',
 qr_image text NOT NULL DEFAULT '', email text NOT NULL DEFAULT '',
 notification_topics text[] NOT NULL DEFAULT '{}', notify_all boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now(), updated_at timestamptz NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX IF NOT EXISTS one_admin ON merchants(is_admin) WHERE is_admin;
CREATE TABLE IF NOT EXISTS merchant_apps (
 merchant_id bigint NOT NULL REFERENCES merchants(id), name text NOT NULL,
 merchant_key text NOT NULL, enabled boolean NOT NULL DEFAULT true,
 payment_note text NOT NULL DEFAULT '', deleted_at timestamptz,
 created_at timestamptz NOT NULL DEFAULT now(), PRIMARY KEY(merchant_id,name),
 UNIQUE(merchant_id,merchant_key)
);
CREATE TABLE IF NOT EXISTS notification_subscriptions (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, merchant_id bigint NOT NULL REFERENCES merchants(id),
 email text NOT NULL, topics text[] NOT NULL DEFAULT '{}', apps text[] NOT NULL DEFAULT '{}',
 created_at timestamptz NOT NULL DEFAULT now(), UNIQUE(merchant_id,email)
);
CREATE TABLE IF NOT EXISTS sessions (
 token_hash text PRIMARY KEY, merchant_id bigint NOT NULL REFERENCES merchants(id), expires_at timestamptz NOT NULL
);
CREATE TABLE IF NOT EXISTS devices (
 merchant_id bigint PRIMARY KEY REFERENCES merchants(id), name text NOT NULL,
 token_hash text UNIQUE NOT NULL, installation_id text NOT NULL DEFAULT '', revoked boolean NOT NULL DEFAULT false,
 created_at timestamptz NOT NULL DEFAULT now(), bound_at timestamptz, last_seen timestamptz,
 version text NOT NULL DEFAULT '', model text NOT NULL DEFAULT '', android_version text NOT NULL DEFAULT '',
 battery integer NOT NULL DEFAULT -1 CHECK(battery BETWEEN -1 AND 100), charging boolean NOT NULL DEFAULT false,
 wifi_ssid text NOT NULL DEFAULT '', network text NOT NULL DEFAULT 'unknown', network_validated boolean NOT NULL DEFAULT false,
 listener_connected boolean NOT NULL DEFAULT false, service_running boolean NOT NULL DEFAULT false,
 pending_events integer NOT NULL DEFAULT 0, uptime_seconds bigint NOT NULL DEFAULT 0,
 offline_alerted boolean NOT NULL DEFAULT false, low_battery_alerted boolean NOT NULL DEFAULT false
);
CREATE TABLE IF NOT EXISTS amount_pools (
 merchant_id bigint NOT NULL REFERENCES merchants(id), amount bigint NOT NULL,
 capacity integer NOT NULL DEFAULT 0, PRIMARY KEY(merchant_id,amount)
);
CREATE TABLE IF NOT EXISTS orders (
 trade_no text PRIMARY KEY, merchant_id bigint NOT NULL REFERENCES merchants(id), app_id text NOT NULL DEFAULT '', username text NOT NULL DEFAULT '', out_trade_no text NOT NULL,
 name text NOT NULL, amount bigint NOT NULL CHECK(amount>0), pay_amount bigint NOT NULL CHECK(pay_amount>0 AND pay_amount<=amount),
 discount integer NOT NULL CHECK(discount>=0), merchant_key text NOT NULL,
 notify_url text NOT NULL, return_url text NOT NULL DEFAULT '', param text NOT NULL DEFAULT '', qr_image text NOT NULL, payment_note text NOT NULL DEFAULT '',
 status text NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','paid','expired')),
 created_at timestamptz NOT NULL DEFAULT clock_timestamp(), expires_at timestamptz NOT NULL,
 paid_at timestamptz, event_id text UNIQUE,
 callback_status text NOT NULL DEFAULT 'waiting', callback_attempts integer NOT NULL DEFAULT 0,
 callback_next_at timestamptz, callback_locked_until timestamptz, callback_result text NOT NULL DEFAULT '',
 UNIQUE(merchant_id,app_id,out_trade_no)
);
CREATE UNIQUE INDEX IF NOT EXISTS active_pay_amount ON orders(merchant_id,pay_amount) WHERE status='pending';
CREATE INDEX IF NOT EXISTS orders_history ON orders(merchant_id,created_at DESC);
CREATE INDEX IF NOT EXISTS orders_callback_idx ON orders(callback_next_at) WHERE status='paid' AND callback_status IN ('pending','retrying');
CREATE TABLE IF NOT EXISTS events (
 id text PRIMARY KEY, merchant_id bigint NOT NULL REFERENCES merchants(id), fingerprint text NOT NULL,
 notification_id text NOT NULL, raw_text text NOT NULL, payer text NOT NULL DEFAULT '', amount bigint NOT NULL DEFAULT 0,
 posted_at timestamptz NOT NULL, received_at timestamptz NOT NULL DEFAULT now(), status text NOT NULL,
 reason text NOT NULL DEFAULT '', trade_no text REFERENCES orders(trade_no), UNIQUE(merchant_id,fingerprint)
);
CREATE TABLE IF NOT EXISTS smtp_settings (
 id boolean PRIMARY KEY DEFAULT true CHECK(id), enabled boolean NOT NULL DEFAULT false,
 host text NOT NULL DEFAULT '', port integer NOT NULL DEFAULT 587, username text NOT NULL DEFAULT '', password text NOT NULL DEFAULT '',
 from_address text NOT NULL DEFAULT '', from_name text NOT NULL DEFAULT 'ANE', security text NOT NULL DEFAULT 'starttls',
 updated_at timestamptz NOT NULL DEFAULT now()
);
INSERT INTO smtp_settings(id) VALUES(true) ON CONFLICT DO NOTHING;
CREATE TABLE IF NOT EXISTS notification_events (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, merchant_id bigint NOT NULL REFERENCES merchants(id),
 app_id text, topic text NOT NULL, dedupe_key text UNIQUE NOT NULL, title text NOT NULL, message text NOT NULL,
 created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE IF NOT EXISTS mail_queue (
 id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY, event_id bigint REFERENCES notification_events(id),
 subscription_id bigint REFERENCES notification_subscriptions(id) ON DELETE SET NULL,
 recipient_id bigint NOT NULL REFERENCES merchants(id), recipient text NOT NULL, subject text NOT NULL, body text NOT NULL,
 status text NOT NULL DEFAULT 'pending', attempts integer NOT NULL DEFAULT 0, next_at timestamptz NOT NULL DEFAULT now(),
 locked_until timestamptz, last_error text NOT NULL DEFAULT '', created_at timestamptz NOT NULL DEFAULT now(), sent_at timestamptz,
 UNIQUE(event_id,recipient_id,recipient)
);
CREATE INDEX IF NOT EXISTS mail_queue_pending ON mail_queue(next_at) WHERE status IN ('pending','retrying');
